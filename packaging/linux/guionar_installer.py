class Instalador:
    def __init__(self, origen: Origen, destino: Destino,
                 herramientas: Herramientas | None = None):
        self.origen = origen
        self.destino = destino
        self.h = herramientas or Herramientas()

    def verificar_propiedad(self) -> str:
        d = self.destino
        for enlace, target in d.enlaces().items():
            if not os.path.lexists(enlace):
                continue
            actual = re.sub(r"/+", "/", os.readlink(enlace)) \
                if enlace.is_symlink() else None
            if actual != str(target):
                raise ErrorInstalacion(
                    f"{enlace} existe y no pertenece a esta instalación")
        estado = estado_desktop(d.desktop)
        if estado == "ajeno":
            raise ErrorInstalacion(
                f"{d.desktop} ya existe y no fue generado por GuionAR; "
                "no se reemplaza")
        if d.install_home.is_symlink():
            raise ErrorInstalacion(
                f"la raíz de instalación es un enlace simbólico: {d.install_home}")
        if os.path.lexists(d.current) and not d.current.is_symlink():
            raise ErrorInstalacion(f"{d.current} no es un enlace de GuionAR")
        return estado

    def _entorno_smoke(self, temporal: Path) -> dict[str, str]:
        entorno = {k: v for k, v in os.environ.items()
                   if k in {"PATH", "LANG", "LC_ALL", "HOME"}}
        runtime = temporal / "run"
        runtime.mkdir(mode=0o700)
        entorno.update({
            "QT_QPA_PLATFORM": "offscreen",
            "XDG_CONFIG_HOME": str(temporal / "config"),
            "XDG_RUNTIME_DIR": str(runtime),
        })
        return entorno

    def _preparar(self, version_dir: Path) -> None:
        app = version_dir / "app"
        venv = version_dir / ".venv"
        python = venv / "bin" / "python"
        info("Copiando la aplicación")
        shutil.copytree(self.origen.app, app, symlinks=False)
        (app / "bin" / "guionar").chmod(0o755)

        info(f"Creando entorno aislado {version_dir.name}")
        self.h.crear_venv(venv)
        info("Instalando PyQt6")
        if not self.h.pip_install(python, [
                "-c", str(self.origen.constraints),
                "--only-binary=:all:", "PyQt6"]):
            raise ErrorInstalacion("pip no pudo instalar PyQt6")

        info("Validando PyQt6, QtPdf y GuionAR")
        with tempfile.TemporaryDirectory(prefix="guionar-smoke-") as tmp:
            entorno = self._entorno_smoke(Path(tmp))
            for descripcion, comando in (
                    ("PyQt6", [str(python), "-I", "-c",
                               "import PyQt6.QtCore, PyQt6.QtGui, "
                               "PyQt6.QtWidgets"]),
                    ("QtPdf", [str(python), "-I", "-c",
                               "from PyQt6.QtPdf import QPdfDocument"]),
                    ("smoke", [str(python), "-I", "-c", SMOKE, str(app)])):
                resultado = self.h.ejecutar(comando, entorno)
                if resultado.returncode != 0:
                    raise ErrorInstalacion(
                        f"validación de {descripcion} falló:\n"
                        + (resultado.stderr or resultado.stdout).strip()[-2000:])
            resultado = self.h.ejecutar(
                [str(app / "bin" / "guionar"), "--version"], entorno)
        esperado = f"{APP} {self.origen.version}"
        if resultado.returncode != 0 or resultado.stdout.strip() != esperado:
            raise ErrorInstalacion(
                f"guionar --version devolvió {resultado.stdout.strip()!r}; "
                f"se esperaba {esperado!r}")

    def _publicar(self, estado_desktop_previo: str) -> None:
        d = self.destino
        for enlace, target in d.enlaces().items():
            if not (enlace.is_symlink() and os.readlink(enlace) == str(target)):
                symlink_atomico(enlace, str(target))

        plantilla = (self.origen.packaging / "guionar.desktop.in").read_text(
            encoding="utf-8")
        escribir_atomico(
            d.desktop, renderizar_desktop(plantilla, d.lanzador).encode(), 0o644)
        if estado_desktop_previo == "legacy":
            info("Launcher anterior reemplazado; la copia del repositorio "
                 "no se modificó")
        info(f"Launcher en el menú: {d.desktop}")

        icono = (self.origen.app / "assets" / "guionar.svg").read_bytes()
        if (not d.icono.exists() or d.icono.is_symlink()
                or estado_desktop_previo in {"propio", "legacy"}
                or d.icono.read_bytes() == icono):
            if d.icono.is_symlink():
                d.icono.unlink()
            escribir_atomico(d.icono, icono, 0o644)
        else:
            aviso(f"{d.icono} existe y no es de GuionAR; se conserva")

        for comando in (
                ["update-desktop-database", str(d.desktop.parent)],
                ["gtk-update-icon-cache", "-q", "-t", str(d.icono.parents[2])]):
            if shutil.which(comando[0]):
                self.h.ejecutar(comando)

    def _escribir_metadata(self, version_dir: str, previous: str | None) -> None:
        datos = {
            "app": APP,
            "version": self.origen.version,
            "current": version_dir,
            "previous": previous,
            "installed_at": _dt.datetime.now(_dt.timezone.utc)
            .replace(microsecond=0).isoformat().replace("+00:00", "Z"),
        }
        escribir_atomico(self.destino.metadata,
                         (json.dumps(datos, indent=2) + "\n").encode(), 0o644)

    def _podar(self, conservar: set[str]) -> None:
        for entrada in sorted(self.destino.versions.iterdir()):
            if (f"versions/{entrada.name}" in conservar
                    or entrada.is_symlink() or not entrada.is_dir()):
                continue
            if NOMBRE_VERSION.match(entrada.name) and (
                    entrada / MARCA_VERSION).is_file():
                info(f"Eliminando versión antigua {entrada.name}")
                shutil.rmtree(entrada)

    def _current_previo(self) -> str | None:
        d = self.destino
        if not d.current.is_symlink():
            return None
        target = os.readlink(d.current)
        partes = target.split("/")
        if not (len(partes) == 2 and partes[0] == "versions"
                and NOMBRE_VERSION.match(partes[1])):
            raise ErrorInstalacion(
                f"{d.current} apunta a un destino no administrado: {target}")
        return target if (d.install_home / target).is_dir() else None

    def instalar(self) -> tuple[str, str | None]:
        d = self.destino
        estado = self.verificar_propiedad()
        verificar_espacio(d.install_home, ESPACIO_MINIMO)
        raiz_nueva = not d.install_home.exists()
        d.install_home.mkdir(parents=True, exist_ok=True)
        with bloqueo(d.install_home):
            previous = self._current_previo()
            versions_nuevo = not d.versions.exists()
            d.versions.mkdir(exist_ok=True)
            nombre = f"{self.origen.version}-{secrets.token_hex(4)}"
            version_dir = d.versions / nombre
            version_dir.mkdir()
            (version_dir / MARCA_INCOMPLETA).write_text("", encoding="utf-8")
            (version_dir / MARCA_VERSION).write_text(
                f"{APP} {self.origen.version}\n", encoding="utf-8")
            try:
                self._preparar(version_dir)
                (version_dir / MARCA_INCOMPLETA).unlink()
            except BaseException:
                aviso("La instalación nueva falló; se descarta sin tocar la "
                      "instalación vigente")
                shutil.rmtree(version_dir, ignore_errors=True)
                for vacio, creado in ((d.versions, versions_nuevo),
                                      (d.install_home, raiz_nueva)):
                    if creado:
                        with contextlib.suppress(OSError):
                            vacio.rmdir()
                raise

            relativo = f"versions/{nombre}"
            symlink_atomico(d.current, relativo)
            self._publicar(estado)
            escribir_atomico(d.uninstall, self.origen.uninstall.read_bytes(),
                             0o755)
            self._escribir_metadata(relativo, previous)
            self._podar({relativo} | ({previous} if previous else set()))
        return relativo, previous


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="install.sh")
    parser.add_argument("--origen", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        origen = detectar_origen(args.origen)
        verificar_python(origen)
        destino = Destino.desde_entorno()
        _relativo, previous = Instalador(origen, destino).instalar()
    except ErrorInstalacion as exc:
        aviso(str(exc))
        return 1
    except (OSError, ValueError, subprocess.SubprocessError) as exc:
        aviso(f"la instalación falló: {exc}")
        return 1
    except KeyboardInterrupt:
        aviso("instalación interrumpida; la instalación vigente no cambió")
        return 130

    info(f"GuionAR {origen.version} instalado. Comandos: "
         f"{destino.bin_dir}/{COMANDO} y {destino.bin_dir}/{COMANDO_UNINSTALL}")
    if previous:
        print("    Si GuionAR está abierto, cerralo y volvé a abrirlo desde el "
              f"menú para usar {origen.version}.")
    if f":{destino.bin_dir}:" not in f":{os.environ.get('PATH', '')}:":
        aviso(f"{destino.bin_dir} no está en PATH; agregalo para invocar los "
              "comandos por nombre")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
