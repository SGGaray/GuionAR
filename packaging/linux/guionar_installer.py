#!/usr/bin/env python3
"""Instalador de usuario de GuionAR desde la release extraída.

Lo invoca ``install.sh`` con un Python ya validado. Layout administrado bajo
``$XDG_DATA_HOME/guionar``::

    versions/<versión>-<id>/app/    módulos, bin/, assets/ y packaging/
    versions/<versión>-<id>/.venv/  PyQt6 fijado por constraints.txt
    current -> versions/<...>       symlink relativo, reemplazo atómico
    installed.json                  metadata mínima, escritura atómica
    uninstall.sh                    desinstalador independiente del release

Todo lo previo al swap ocurre en un directorio nuevo. Si algo falla, ese
directorio se elimina y ``current``, enlaces y launcher quedan como estaban.
La configuración (``~/.config/guionar``) nunca se toca, y tampoco una copia
del repositorio que se haya usado antes para abrir GuionAR.
"""

from __future__ import annotations

import argparse
import contextlib
from dataclasses import dataclass
import datetime as _dt
import fcntl
import json
import os
from pathlib import Path
import re
import secrets
import shutil
import subprocess
import sys
import tempfile

APP = "GuionAR"
MARCA_DESKTOP = ("# Generated by GuionAR install.sh. "
                 "Local edits may be replaced by a later install.")
MARCA_INCOMPLETA = ".guionar-incomplete"
MARCA_VERSION = ".guionar-version"  # bin/guionar la usa para hallar .venv
NOMBRE_VERSION = re.compile(r"^[0-9][0-9A-Za-z.+]*-[0-9a-f]{8}$")
MIB = 1024 * 1024
ESPACIO_MINIMO = 768 * MIB
COMANDO = "guionar"
COMANDO_UNINSTALL = "guionar-uninstall"
# Plantilla que usaba packaging/linux/install-desktop-entry.sh. Un launcher
# sólo se considera legacy propio si coincide con ella línea por línea y su
# Exec apunta a */bin/guionar --socket.
PLANTILLA_LEGACY = """[Desktop Entry]
Type=Application
Version=1.5
Name=GuionAR
GenericName=Teleprompter
Comment=Teleprompter flotante para leer un guion frente a la cámara
Exec=@EXEC@ --socket
Icon=guionar
Terminal=false
StartupNotify=false
Categories=AudioVideo;Video;
Keywords=teleprompter;guion;prompter;script;ParlAR;
"""
# Dentro de comillas cada " ` $ \\ lleva una barra y después la regla de
# strings duplica cada barra: un carácter especial queda como \\\\X.
_EXEC_LEGACY = re.compile(
    r'^Exec="(/(?:[^"\\`$]|\\\\(?:\\\\|["`$]))*/bin/guionar)" --socket$')
SMOKE = r"""
import os, sys
sys.path.insert(0, sys.argv[1])
from PyQt6.QtWidgets import QApplication
import bridge, desktop_shell, document_loader, guion, guionar
app = QApplication([])
overlay = guionar.TeleprompterOverlay(None, persistir=False)
overlay.show()
overlay.append_text("prueba")
app.processEvents()
overlay.close()
app.processEvents()
print("smoke-ok")
"""


class ErrorInstalacion(RuntimeError):
    """Fallo controlado: el mensaje es para la persona usuaria."""


def info(mensaje: str) -> None:
    print(f"==> {mensaje}", flush=True)


def aviso(mensaje: str) -> None:
    print(f"!! {mensaje}", file=sys.stderr, flush=True)


# ---------------------------------------------------------------------------
# Origen y destino
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class Origen:
    raiz: Path
    version: str

    @property
    def app(self) -> Path:
        return self.raiz / "app"

    @property
    def packaging(self) -> Path:
        return self.app / "packaging" / "linux"

    @property
    def constraints(self) -> Path:
        return self.raiz / "constraints.txt"

    @property
    def uninstall(self) -> Path:
        return self.raiz / "uninstall.sh"


def leer_version_app(app: Path) -> str:
    texto = (app / "guionar_version.py").read_text(encoding="utf-8")
    coincidencia = re.search(r'^__version__ = "([^"]+)"$', texto, re.M)
    if not coincidencia:
        raise ErrorInstalacion("guionar_version.py sin __version__")
    return coincidencia[1]


def detectar_origen(raiz: Path) -> Origen:
    raiz = raiz.resolve()
    if not ((raiz / "VERSION").is_file() and (raiz / "app").is_dir()):
        raise ErrorInstalacion(
            f"{raiz} no es una release de GuionAR. Descargá la release "
            "desde https://github.com/SGGaray/GuionAR/releases")
    version = (raiz / "VERSION").read_text(encoding="utf-8").strip()
    if leer_version_app(raiz / "app") != version:
        raise ErrorInstalacion("VERSION no coincide con la app; descargá "
                               "la release de nuevo")
    return Origen(raiz, version)


def versiones_python(origen: Origen) -> list[str]:
    archivo = origen.packaging / "python-versions.txt"
    return [linea.strip() for linea in archivo.read_text(
        encoding="utf-8").splitlines() if linea.strip()]


def verificar_python(origen: Origen) -> None:
    versiones = versiones_python(origen)
    if "%d.%d" % sys.version_info[:2] not in versiones:
        raise ErrorInstalacion(
            f"Esta versión de GuionAR soporta Python {versiones[0]}–"
            f"{versiones[-1]}.\nInstalá una versión compatible o descargá "
            "una release más nueva.")


def _sin_separadores_finales(valor: str) -> str:
    while valor != "/" and valor.endswith("/"):
        valor = valor[:-1]
    return valor


def validar_install_home(original: str, home: str) -> Path:
    valor = _sin_separadores_finales(original)
    partes = valor.split("/")
    ruta = Path(valor)
    if ("." in partes or ".." in partes or not ruta.is_absolute()
            or ruta.name != "guionar" or str(ruta.parent) == "/"
            or valor == _sin_separadores_finales(home)):
        raise ErrorInstalacion(f"ruta de instalación insegura: {original}")
    return ruta


@dataclass(frozen=True)
class Destino:
    home: Path
    install_home: Path
    bin_dir: Path
    desktop: Path
    icono: Path

    @classmethod
    def desde_entorno(cls, entorno=os.environ) -> "Destino":
        home = entorno.get("HOME", "")
        if not home or not os.path.isabs(home):
            raise ErrorInstalacion("HOME no está definido como ruta absoluta")
        data = Path(entorno.get("XDG_DATA_HOME") or f"{home}/.local/share")
        return cls(
            home=Path(home),
            install_home=validar_install_home(
                entorno.get("GUIONAR_INSTALL_HOME") or str(data / "guionar"),
                home),
            bin_dir=Path(entorno.get("GUIONAR_BIN_DIR")
                         or f"{home}/.local/bin"),
            desktop=data / "applications" / "guionar.desktop",
            icono=data / "icons" / "hicolor" / "scalable" / "apps" / "guionar.svg",
        )

    @property
    def versions(self) -> Path:
        return self.install_home / "versions"

    @property
    def current(self) -> Path:
        return self.install_home / "current"

    @property
    def metadata(self) -> Path:
        return self.install_home / "installed.json"

    @property
    def uninstall(self) -> Path:
        return self.install_home / "uninstall.sh"

    @property
    def lanzador(self) -> Path:
        """Ruta estable entre versiones: atraviesa ``current``."""
        return self.current / "app" / "bin" / "guionar"

    def enlaces(self) -> dict[Path, Path]:
        return {self.bin_dir / COMANDO: self.lanzador,
                self.bin_dir / COMANDO_UNINSTALL: self.uninstall}


# ---------------------------------------------------------------------------
# Launcher
# ---------------------------------------------------------------------------


def argumento_exec(ruta: Path) -> str:
    """Exec entre comillas según la especificación Desktop Entry."""
    texto = str(ruta)
    if not ruta.is_absolute():
        raise ErrorInstalacion("el ejecutable del launcher debe ser absoluto")
    if any(ord(c) < 32 or ord(c) == 127 for c in texto):
        raise ErrorInstalacion("el ejecutable contiene caracteres de control")
    # Mismo escape que install-desktop-entry.sh: regla de comillas, regla
    # de strings (duplica barras) y, además, % de los field codes.
    texto = re.sub(r'([\\"`$])', r"\\\1", texto)
    texto = texto.replace("\\", "\\\\").replace("%", "%%")
    return f'"{texto}"'


def renderizar_desktop(plantilla: str, lanzador: Path) -> str:
    if plantilla.count("@EXEC@") != 1:
        raise ErrorInstalacion("plantilla .desktop sin placeholder único")
    return f"{MARCA_DESKTOP}\n" + plantilla.replace(
        "@EXEC@", argumento_exec(lanzador))


def es_desktop_legacy(contenido: str) -> bool:
    """Reconoce sólo el launcher exacto de install-desktop-entry.sh."""
    esperadas = PLANTILLA_LEGACY.splitlines()
    lineas = contenido.splitlines()
    if len(lineas) != len(esperadas) or not contenido.endswith("\n"):
        return False
    for linea, esperada in zip(lineas, esperadas):
        if "@EXEC@" in esperada:
            if not _EXEC_LEGACY.match(linea):
                return False
        elif linea != esperada:
            return False
    return True


def estado_desktop(ruta: Path) -> str:
    """'ausente', 'propio', 'legacy' o 'ajeno'."""
    if not os.path.lexists(ruta):
        return "ausente"
    if ruta.is_symlink() or not ruta.is_file():
        return "ajeno"
    try:
        contenido = ruta.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return "ajeno"
    if contenido.startswith(MARCA_DESKTOP + "\n"):
        return "propio"
    if es_desktop_legacy(contenido):
        return "legacy"
    return "ajeno"


# ---------------------------------------------------------------------------
# Operaciones atómicas
# ---------------------------------------------------------------------------


def escribir_atomico(destino: Path, contenido: bytes, modo: int) -> None:
    destino.parent.mkdir(parents=True, exist_ok=True)
    temporal = destino.with_name(f".{destino.name}.tmp-{secrets.token_hex(4)}")
    descriptor = os.open(temporal, os.O_WRONLY | os.O_CREAT | os.O_EXCL, modo)
    try:
        with os.fdopen(descriptor, "wb") as archivo:
            archivo.write(contenido)
            archivo.flush()
            os.fsync(archivo.fileno())
        os.chmod(temporal, modo)
        os.replace(temporal, destino)
    except BaseException:
        with contextlib.suppress(FileNotFoundError):
            temporal.unlink()
        raise


def symlink_atomico(destino: Path, target: str) -> None:
    destino.parent.mkdir(parents=True, exist_ok=True)
    temporal = destino.with_name(f".{destino.name}.tmp-{secrets.token_hex(4)}")
    os.symlink(target, temporal)
    try:
        os.replace(temporal, destino)
    except BaseException:
        with contextlib.suppress(FileNotFoundError):
            temporal.unlink()
        raise


@contextlib.contextmanager
def bloqueo(ruta: Path):
    """flock sobre el directorio raíz: no deja archivos de lock."""
    descriptor = os.open(ruta, os.O_RDONLY | os.O_DIRECTORY)
    try:
        try:
            fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise ErrorInstalacion(
                "hay otra instalación de GuionAR en curso") from None
        yield
    finally:
        os.close(descriptor)


def verificar_espacio(ruta: Path, minimo: int) -> None:
    existente = ruta
    while not existente.exists():
        existente = existente.parent
    libre = shutil.disk_usage(existente).free
    if libre < minimo:
        raise ErrorInstalacion(
            f"espacio insuficiente en {existente}: libres {libre // MIB} MiB, "
            f"se necesitan al menos {minimo // MIB} MiB")


