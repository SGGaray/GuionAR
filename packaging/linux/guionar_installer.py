class Herramientas:
    """Única frontera con venv/pip/subprocesos; todo con cwd ``/``."""

    def crear_venv(self, destino: Path) -> None:
        subprocess.run([sys.executable, "-m", "venv", str(destino)],
                       check=True, cwd="/")

    def pip_install(self, python: Path, argumentos: list[str]) -> bool:
        comando = [str(python), "-m", "pip", "install",
                   "--disable-pip-version-check", "--no-input", *argumentos]
        return subprocess.run(comando, check=False, cwd="/").returncode == 0

    def ejecutar(self, comando: list[str],
                 entorno: dict[str, str] | None = None
                 ) -> subprocess.CompletedProcess:
        return subprocess.run(
            comando, check=False, text=True, capture_output=True,
            timeout=120, cwd="/", env=entorno)


